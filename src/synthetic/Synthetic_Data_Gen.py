# ─────────────────────────────────────────────
# 3. Euler-Maruyama SDE integrator
# ─────────────────────────────────────────────

def integrate_sde(rhs, x0, t, params, sigma, rng, phi_ar=0.0, mu_sweep=None):
    """
    Euler-Maruyama integration of dx = f(x,t,params)dt + sigma*dW.
    Returns trajectory array of length len(t).
    Clips to [-10, 10] to avoid blow-up.

    Parameters
    ----------
    phi_ar   : AR(1) correlation coefficient (0 = white noise).
               Noise is η[i] = phi_ar*η[i-1] + ε[i], ε ~ N(0,1).
               noise_term = sigma * η[i] * sqrt(|dt|).
    mu_sweep : optional array of length len(t); if provided, overrides
               params['mu'] at each step i with mu_sweep[i].
    """
    dt = np.diff(t)
    x  = np.zeros(len(t))
    x[0] = x0
    eta = 0.0   # AR(1) state
    for i, dti in enumerate(dt):
        eps = rng.normal(0.0, 1.0)
        eta = phi_ar * eta + eps
        noise_term = sigma * eta * np.sqrt(abs(dti))
        step_params = dict(params)
        if mu_sweep is not None:
            step_params['mu'] = mu_sweep[i]
        x[i+1] = x[i] + rhs(x[i], t[i], **step_params) * dti + noise_term
        x[i+1] = np.clip(x[i+1], -10, 10)
    return x


