"""
Phase 1 — Synthetic Data Generator  (v2 — hard 150K 3-class)
=============================================================
Generates labeled time series for three bifurcation classes:
  0 — Saddle-node:    dx/dt = mu + x^2   (+higher order), mu swept through fold.
                      Parameter sweeps from stable regime to past the bifurcation →
                      critical slowing down (rising variance/AC) then rapid escape.
  1 — Transcritical:  dx/dt = mu*x - x^2 (+higher order), mu in bifurcating regime.
                      System starts near x=0 (unstable FP) and rises to saturation.
  2 — Null (Option C): 0→1 rising trajectory generated by a constant-parameter
                      NON-BIFURCATING ODE.  Three sub-types (equal probability):
                        A. Exponential saturation: dx/dt = r*(1-x)
                           Shape: concave-down, no inflection.
                        B. Linear ramp:            dx/dt = c (constant drift)
                           Shape: straight-line rise.  Zero curvature everywhere.
                        C. Partial expsat:         dx/dt = r*(x_sat - x), x_sat∈[0.25,0.75]
                           Shape: concave-down (same as A after normalization), but
                           represents niche adoption that stalls at partial penetration.

  INFLECTION POSITION DESIGN (v2):
  ─────────────────────────────────────────────────────────────────────────────
  v1 had TC inflection locked at exactly x≈0.50 (quadratic symmetry, a3≈0).
  v2 expands a3 range for TC and extends SN speed range downward, creating
  genuine overlap in the inflection-position feature dimension:

    TC  (v2):  a3 ∈ (-0.5, 0.5)  →  inflection ∈ [0.40, 0.62]
               Validation: inflection_position(x_500) < 0.65 (else retry)
    SN  (v2):  speed ∈ (0.3, 5.0) →  inflection ∈ [0.52, 0.85]
               Validation: inflection_position(x_500) > 0.50 (else retry)
    Overlap:   [0.52, 0.62]

  In the overlap region shape alone cannot discriminate SN from TC.  The model
  must learn CSD statistics (rising variance / rising AC during the pre-inflection
  phase for SN; flat statistics for TC).

  NOISE (v2 hard variant):
  ─────────────────────────────────────────────────────────────────────────────
  noise_levels extended to [0.005, 0.01, 0.02, 0.05, 0.10, 0.15, 0.20].
  phi_ar (AR(1) noise colour): SN/TC sampled from [0.0, 0.9]; Null from [0.0, 0.7].

  NULL CLASS HISTORY:
  ─────────────────────────────────────────────────────────────────────────────
  Option A (original): flat equilibrium fluctuations — trivially distinguishable
    by shape ("not rising → null"); model learned speed-based discrimination.
  Option B: expsat + Gompertz + Richards — Gompertz (inflection x≈0.37) and
    Richards (inflection x≈0.09–0.38) retired 2026-05-05 because their inflection
    points fall directly in SN feature-space territory, blurring the SN centroid.
  Option C (current): expsat + linear_ramp + partial_expsat.
    All three have no inflection in the SN/TC zone (x∈[0.40,0.62]).
    Teaches the model that the ABSENCE of a correctly-positioned S-curve inflection
    combined with flat CSD statistics → inconclusive.

Each sample is PCHIP-interpolated to exactly TARGET_POINTS = 500 uniform
grid points — identical to the real-world curation pipeline.

Default dataset: 150,000 samples (50,000 per class).
  → data/synthetic_150k_3class/X_full.npy   (150000, 500) float32
  → data/synthetic_150k_3class/y.npy         labels (0/1/2)
  → data/synthetic_150k_3class/metadata.json
  → data/synthetic_150k_3class/synthetic_dataset.pkl

Stage-1 centroid init uses 2-class subset: filter y < 2  →  100K (SN+TC only).

Usage:
    python Synthetic_Data_Gen.py                    # generates 150K to default path
    python Synthetic_Data_Gen.py --n 30000          # smaller run for testing
    python Synthetic_Data_Gen.py --out data/custom/ # custom output path

    from Synthetic_Data_Gen import SyntheticBifurcationDataset
    dataset = SyntheticBifurcationDataset(n_samples=150_000)
    dataset.generate()
    dataset.save("data/synthetic_150k_3class/")
"""

