# 2. ODE right-hand sides
# ─────────────────────────────────────────────

# ── Bifurcating ODEs (SN and TC) ──────────────────────────────────────────────

def saddle_node_rhs(x, t, mu, a2=1.0, a3=0.0):
    """
    Saddle-node normal form: dx/dt = mu + a2*x^2 + a3*x^3
    Used with a mu_sweep so the parameter crosses the fold during the simulation.
    """
    return mu + a2 * x**2 + a3 * x**3


def transcritical_rhs(x, t, mu, a2=1.0, a3=0.0):
    """
    Transcritical normal form: dx/dt = mu*x - a2*x^2 + a3*x^3
    Exchange of stability at x=0 when mu crosses 0.  Fixed mu > 0 gives clean
    logistic rise from x≈0 to x=mu/a2 with an S-curve inflection at x≈mu/(2*a2).

    v2: a3 range extended to (-0.5, 0.5) to shift inflection from locked x≈0.50
    to a range [0.40, 0.62], creating genuine TC/SN overlap in inflection space.
    Validation in _generate_one rejects samples with inflection ≥ 0.65.
    """
    return mu * x - a2 * x**2 + a3 * x**3


# ── Null ODEs (Option C) — 0→1 rising, NO bifurcation, NO CSD ────────────────

def null_expsat_rhs(x, t, r):
    """
    Exponential saturation: dx/dt = r*(1-x).
    Stable FP at x=1.  Solution: x(t) = 1 - (1-x0)*exp(-r*t).
    Shape: CONCAVE-DOWN — derivative maximal at t=0, decays monotonically.
    No inflection point.  Eigenvalue at attractor = -r (constant → no CSD).
    r ∈ [0.5, 3.0].
    """
    return r * (1.0 - x)


def null_linear_ramp_rhs(x, t, c):
    """
    Linear ramp + hard plateau: dx/dt = c  while x < 1, else 0.
    Trajectory rises at constant rate c from x0 until x=1, then flat.
    No fixed point during rise, no eigenvalue → ZERO CSD by construction.
    Shape: straight-line rise followed by a plateau.
    c chosen so plateau starts at ~25–67% of t_end → plateau check always passes.
    """
    return float(c) if float(x) < 1.0 else 0.0


def null_partial_expsat_rhs(x, t, r, x_sat):
    """
    Partial exponential saturation: dx/dt = r*(x_sat - x), x_sat ∈ [0.25, 0.75].
    Stable FP at x = x_sat (niche adoption stall below full market penetration).
    After min-max normalization to [0,1]: shape is concave-down, identical in
    form to full expsat — the normalization maps x_sat → 1.0.
    Eigenvalue = -r (constant → no CSD).
    Represents technologies that capture partial market share and stall.
    r ∈ [0.5, 3.0], x_sat ∈ [0.25, 0.75].
    """
    return r * (float(x_sat) - float(x))


def null_sigmoid_template(rng, n_steps, t_end=None):
    """
    Deterministic generalized-logistic ('Richards') sigmoid whose inflection TIME
    is drawn anywhere in [0, 1], used as a NULL (no bifurcation).  Returned as a
    precomputed trajectory; the caller adds STATIONARY, constant-variance noise, so
    there is NO critical slowing down (variance / autocorrelation do not rise toward
    the takeoff) even though the curve has an S-shaped inflection that can coincide
    with the SN or TC inflection.  This removes inflection position/timing as a class
    cue, forcing any null-vs-bifurcation separation to rely on the noise dynamics.

    Returns x_det (length n_steps), rising from ~0 to ~1.
    """
    tau   = np.linspace(0.0, 1.0, n_steps)
    t_inf = rng.uniform(0.08, 0.80)            # inflection TIME (kept < 0.8 so it can plateau)
    k     = rng.uniform(8.0, 26.0)             # steepness
    nu    = rng.uniform(0.4, 2.5)              # asymmetry (nu != 1 => not the TC normal form)
    x = (1.0 / (1.0 + np.exp(-k * (tau - t_inf)))) ** nu
    x = x - x.min()
    return x / (x.max() + 1e-12)


