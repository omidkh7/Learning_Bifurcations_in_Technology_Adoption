def plot_samples(dataset: SyntheticBifurcationDataset, n_per_class: int = 5,
                 save_path: str = None):
    """
    Plot n_per_class example trajectories for each bifurcation class.
    Shows the 500-pt PCHIP series (solid) with the raw ODE trajectory
    overlaid as dots.  Also marks the inflection point position.
    """
    try:
        import matplotlib.pyplot as plt
    except ImportError:
        print("matplotlib not available — skipping plot.")
        return

    colors = {0: "#E63946", 1: "#2196F3", 2: "#4CAF50"}
    titles = {
        0: "Saddle-Node\n(inflection [0.52, 0.85])",
        1: "Transcritical\n(inflection [0.40, 0.62])",
        2: "Null — Option C\n(no S-curve inflection)",
    }

    fig, axes = plt.subplots(3, n_per_class, figsize=(3 * n_per_class, 9))
    fig.suptitle(
        f"Synthetic Dataset v2 (Option C null, hard variant) — {TARGET_POINTS}-pt PCHIP\n"
        "(solid = interpolated, dots = raw ODE, ▲ = inflection point)",
        fontsize=11, fontweight="bold",
    )

    for label in range(3):
        class_samples = [s for s in dataset.samples if s.label == label][:n_per_class]
        for j, s in enumerate(class_samples):
            ax     = axes[label][j]
            t_500  = np.linspace(0, 1, TARGET_POINTS)
            t_raw  = np.linspace(0, 1, len(s.x_raw))
            infl   = inflection_position(s.x_full)

            ax.plot(t_500, s.x_full, color=colors[label], lw=1.5)
            ax.plot(t_raw, s.x_raw,  ".", color="black", ms=2, alpha=0.4)
            ax.axvline(infl, color="gold", lw=1.0, ls="--", alpha=0.8)

            ax.set_ylim(-0.05, 1.1)
            ax.set_xlim(0, 1)
            ax.set_xticks([]); ax.set_yticks([])
            sub = s.params.get("null_subtype", "")
            if j == 0:
                ax.set_ylabel(titles[label], fontsize=8,
                              fontweight="bold", color=colors[label])
            if label == 0:
                ax.set_title(f"infl={infl:.2f}\nσ={s.noise_level}", fontsize=7)
            elif label == 1:
                ax.set_title(f"infl={infl:.2f}\na3={s.params.get('a3',0):.2f}", fontsize=7)
            elif label == 2:
                ax.set_title(f"{sub}\ninfl={infl:.2f}", fontsize=7)

    plt.tight_layout()
    if save_path:
        plt.savefig(save_path, dpi=150, bbox_inches="tight")
        print(f"Plot saved to {save_path}")
    else:
        plt.show()


def plot_inflection_distributions(dataset: SyntheticBifurcationDataset,
                                   save_path: str = None):
    """
    Histogram of inflection positions per class.
    Shows the designed overlap region [0.52, 0.62] and validates
    that SN and TC do not fully separate in this feature dimension.
    """
    try:
        import matplotlib.pyplot as plt
    except ImportError:
        print("matplotlib not available — skipping plot.")
        return

    labels      = np.array([s.label for s in dataset.samples])
    inflections = np.array([inflection_position(s.x_full) for s in dataset.samples])

    colors = {0: "#E63946", 1: "#2196F3", 2: "#4CAF50"}
    names  = {0: "SN", 1: "TC", 2: "Null"}
    bins   = np.linspace(0.0, 1.0, 51)

    fig, ax = plt.subplots(figsize=(9, 4))
    for lbl in [0, 1, 2]:
        mask = labels == lbl
        ax.hist(inflections[mask], bins=bins, alpha=0.55,
                color=colors[lbl], label=f"{names[lbl]} (n={mask.sum():,})",
                density=True)

    ax.axvspan(0.52, 0.62, alpha=0.12, color="gold",
               label="Overlap zone [0.52, 0.62]")
    ax.axvline(0.50, color="gray",  ls="--", lw=1.2, alpha=0.7)
    ax.axvline(0.65, color="black", ls="--", lw=1.2, alpha=0.7,
               label="TC validation cutoff (0.65)")

    ax.set_xlabel("Normalised inflection position (x*)", fontsize=12)
    ax.set_ylabel("Density", fontsize=12)
    ax.set_title("Inflection Position Distributions — v2 Hard Synthetic Data",
                 fontsize=12, fontweight="bold")
    ax.legend(fontsize=9); ax.grid(alpha=0.3)

    plt.tight_layout()
    if save_path:
        plt.savefig(save_path, dpi=150, bbox_inches="tight")
        print(f"Inflection distribution plot saved to {save_path}")
    else:
        plt.show()


